package com.blanktick.app.collect

import android.content.Context
import android.content.res.AssetManager
import com.blanktick.core.filters.BloomFilter
import com.blanktick.core.filters.SortedHashSet64
import com.blanktick.core.util.IsoDate
import java.io.IOException

/**
 * The intel the scan needs, all of it read from assets inside the APK.
 *
 * @param builtOn ISO date the bundle was generated, shown on every scan.
 * @param stalenessDays age of the bundle relative to the device clock.
 */
data class IntelSnapshot(
    val builtOn: String?,
    val stalenessDays: Int?,
    val referencePatchDates: Map<Int, String>?,
    val knownSigners: Map<String, Set<String>>?
)

/**
 * Loads the bundled threat data.
 *
 * ## Why loading can fail, and why that is fine
 *
 * The heavy assets (a 3.4 MiB password filter, a 16 MiB domain table) are
 * generated by `tools/build_intel.py` and are not committed to source control.
 * A developer build without them must still run — so every accessor here
 * degrades to `null`, and the rules that depend on the missing data report
 * *not checkable* rather than silently passing.
 *
 * That is the same contract the collectors follow, applied to our own data:
 * **absent evidence is never reported as good news.**
 *
 * Assets are declared `noCompress` in `build.gradle.kts`, so on a real device
 * these can be mapped rather than copied. This class reads them eagerly for
 * simplicity; the mmap path is a phase-2 optimisation and is marked as such
 * rather than pretended.
 */
class IntelBundle private constructor(
    val manifest: Manifest?,
    private val breachedPasswords: BloomFilter?,
    private val blockedDomains: SortedHashSet64?,
    private val allowedDomains: SortedHashSet64?,
    private val signers: Map<String, Set<String>>?
) {

    data class Manifest(
        val builtOn: String,
        val passwordCount: Long,
        val domainCount: Int,
        val version: String,
        /**
         * True when the bundle was built from placeholder data rather than real
         * corpora. Surfaced in the UI: a result derived from synthetic data is
         * meaningless, and presenting it as a finding would be the worst kind
         * of false confidence.
         */
        val synthetic: Boolean
    )

    val isComplete: Boolean
        get() = manifest != null && breachedPasswords != null && blockedDomains != null

    fun snapshot(nowIsoDate: String): IntelSnapshot = IntelSnapshot(
        builtOn = manifest?.builtOn,
        stalenessDays = manifest?.builtOn?.let { built ->
            IsoDate.daysBetween(built, nowIsoDate)?.toInt()?.coerceAtLeast(0)
        },
        referencePatchDates = REFERENCE_PATCH_DATES,
        knownSigners = signers
    )

    /**
     * @return null when the corpus is not bundled — the caller must then report
     *   the password check as unavailable, never as "no breaches found".
     */
    fun isPasswordBreached(password: String): Boolean? =
        breachedPasswords?.contains(password)

    fun blocklistMatch(domain: String): String? {
        val blocked = blockedDomains ?: return null
        if (allowedDomains?.matchDomain(domain) != null) return null
        return blocked.matchDomain(domain)
    }

    fun domainAllowlist(): SortedHashSet64? = allowedDomains
    fun domainBlocklist(): SortedHashSet64? = blockedDomains

    companion object {
        private const val DIR = "intel"

        /**
         * Newest security patch level known for each Android major version at
         * the time this build was cut.
         *
         * Compiled in rather than fetched, and used only to measure how far
         * *behind* a device is. When the device is at or ahead of these dates
         * `OsCurrencyRules.PatchLag` makes no claim at all — a stale table can
         * therefore under-report, but it can never invent a problem.
         */
        val REFERENCE_PATCH_DATES: Map<Int, String> = mapOf(
            11 to "2026-08-01",
            12 to "2026-08-01",
            13 to "2026-08-01",
            14 to "2026-08-01",
            15 to "2026-08-01",
            16 to "2026-08-01"
        )

        fun load(context: Context): IntelBundle {
            val assets = context.assets
            return IntelBundle(
                manifest = readManifest(assets),
                breachedPasswords = readAsset(assets, "$DIR/passwords.mub")
                    ?.let { runCatching { BloomFilter.parse(it) }.getOrNull() },
                blockedDomains = readAsset(assets, "$DIR/blocklist.mus")
                    ?.let { runCatching { SortedHashSet64.parse(it) }.getOrNull() },
                allowedDomains = readAsset(assets, "$DIR/allowlist.mus")
                    ?.let { runCatching { SortedHashSet64.parse(it) }.getOrNull() },
                signers = readSigners(assets)
            )
        }

        /** An empty bundle, for tests and for a build with no assets. */
        fun empty(): IntelBundle = IntelBundle(null, null, null, null, null)

        private fun readAsset(assets: AssetManager, path: String): ByteArray? = try {
            assets.open(path).use { it.readBytes() }
        } catch (_: IOException) {
            null
        }

        /**
         * Manifest is a tiny line-oriented format rather than JSON so that the
         * app needs no parser dependency at all (decision D-03).
         *
         *     builtOn=2026-08-20
         *     passwords=2000000
         *     domains=1843221
         *     version=1
         *     synthetic=false
         */
        private fun readManifest(assets: AssetManager): Manifest? {
            val text = readAsset(assets, "$DIR/manifest.txt")?.decodeToString() ?: return null
            val kv = text.lineSequence()
                .mapNotNull { line ->
                    val trimmed = line.trim()
                    if (trimmed.isEmpty() || trimmed.startsWith("#")) return@mapNotNull null
                    val idx = trimmed.indexOf('=')
                    if (idx <= 0) null else trimmed.substring(0, idx) to trimmed.substring(idx + 1)
                }.toMap()

            val builtOn = kv["builtOn"]?.takeIf { IsoDate.isValid(it) } ?: return null
            return Manifest(
                builtOn = builtOn,
                passwordCount = kv["passwords"]?.toLongOrNull() ?: 0L,
                domainCount = kv["domains"]?.toIntOrNull() ?: 0,
                version = kv["version"] ?: "0",
                synthetic = kv["synthetic"]?.equals("true", ignoreCase = true) == true
            )
        }

        /**
         * `signers.txt`: one `packageName<TAB>SHA256[,SHA256...]` per line.
         *
         * Powers clone detection. Plain text because it is small (a few
         * thousand lines) and because a human reviewing a security claim
         * should be able to read the evidence file.
         */
        private fun readSigners(assets: AssetManager): Map<String, Set<String>>? {
            val text = readAsset(assets, "$DIR/signers.txt")?.decodeToString() ?: return null
            val map = text.lineSequence()
                .mapNotNull { line ->
                    val trimmed = line.trim()
                    if (trimmed.isEmpty() || trimmed.startsWith("#")) return@mapNotNull null
                    val parts = trimmed.split('\t', limit = 2)
                    if (parts.size != 2) return@mapNotNull null
                    val hashes = parts[1].split(',')
                        .map { it.trim().uppercase() }
                        .filter { it.length == 64 }
                        .toSet()
                    if (hashes.isEmpty()) null else parts[0] to hashes
                }.toMap()
            return map.ifEmpty { null }
        }
    }
}
