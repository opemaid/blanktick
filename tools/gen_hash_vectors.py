#!/usr/bin/env python3
"""
Generates the canonical hash vectors that pin all three implementations.

    python tools/gen_hash_vectors.py

Writes `shared/hash-vectors.json` and prints ready-to-paste literals for the
Kotlin and Swift test suites.

Why pinned vectors rather than "they look the same"
---------------------------------------------------
Python builds the intel bundle, Kotlin reads it on Android, Swift reads it on
iOS. A one-bit divergence in any of them does not crash -- it silently returns
wrong membership answers, and for the password filter that means telling
someone a breached password is safe.

Reading three implementations side by side cannot prove they agree. Running the
same inputs through all three and comparing fixed hex constants can.
"""

from __future__ import annotations

import json
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from mume_hash import h1, h2  # noqa: E402

ROOT = pathlib.Path(__file__).resolve().parent.parent

# Chosen to exercise the paths that actually differ between languages:
# the empty string, ASCII, multi-byte UTF-8, a NUL byte, a high Latin-1 byte,
# an astral-plane emoji (surrogate pair in UTF-16), and a long input.
VECTORS = [
    "",
    "a",
    "abc",
    "password",
    "123456",
    "münchen",
    "example.com",
    "doubleclick.net",
    "standardbank.co.za",
    "the quick brown fox",
    "\u0000\u00ff",
    "\U0001f512emoji",
    "A" * 64,
]


def kotlin_literal(s: str) -> str:
    out = []
    for ch in s:
        cp = ord(ch)
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "$":
            out.append("\\$")
        elif cp < 0x20 or cp == 0x7F:
            out.append("\\u%04X" % cp)
        elif cp > 0x7E:
            # Escape everything non-ASCII so the source file's own encoding
            # cannot change what is being hashed.
            for unit in ch.encode("utf-16-be"):
                pass
            units = ch.encode("utf-16-be")
            for i in range(0, len(units), 2):
                out.append("\\u%04X" % int.from_bytes(units[i:i + 2], "big"))
        else:
            out.append(ch)
    return "".join(out)


def swift_literal(s: str) -> str:
    out = []
    for ch in s:
        cp = ord(ch)
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif cp < 0x20 or cp == 0x7F or cp > 0x7E:
            out.append("\\u{%X}" % cp)
        else:
            out.append(ch)
    return "".join(out)


def main() -> int:
    payload = {
        "note": ("Generated by tools/gen_hash_vectors.py from tools/mume_hash.py. "
                 "Pinned identically in HashVectorsTest.kt and HashParityTests.swift. "
                 "If any of the three implementations changes, all of these move."),
        "spec": "h1 = splitmix64(fnv1a64(utf8, OFFSET_A)); "
                "h2 = splitmix64(fnv1a64(utf8, OFFSET_B) ^ 0xD6E8FEB86659FD93)",
        "vectors": [
            {"input": v, "h1": "%016X" % h1(v), "h2": "%016X" % h2(v)} for v in VECTORS
        ],
    }

    out = ROOT / "shared" / "hash-vectors.json"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(payload, indent=2, ensure_ascii=False), encoding="utf-8",
                   newline="\n")
    print(f"wrote {out.relative_to(ROOT)} ({len(VECTORS)} vectors)\n")

    print("// ---- Kotlin ----")
    for v in VECTORS:
        print('        Vec("%s", 0x%016XuL, 0x%016XuL),' % (kotlin_literal(v), h1(v), h2(v)))

    print("\n// ---- Swift ----")
    for v in VECTORS:
        print('        ("%s", 0x%016X, 0x%016X),' % (swift_literal(v), h1(v), h2(v)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
