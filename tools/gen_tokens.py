#!/usr/bin/env python3
"""
Generates the three consumers of design/tokens.json (design decision DD-11).

    python tools/gen_tokens.py

Outputs:
    design/tokens.css                      web + prototype + marketing site
    app/src/main/java/.../ui/MumeTokens.kt Android Compose
    desktop/src/main/kotlin/.../ui/MumeTokens.kt Compose Multiplatform (desktop)
    ios/MumeCore/Sources/MumeTokens.swift  SwiftUI

Build-time only. Nothing here ships in the app, and the app never reads JSON at
runtime -- the values are compiled in.

Run it after any edit to tokens.json. `tools/check_tokens.py` fails CI if the
generated files have drifted from the source, so a hand-edited hex value cannot
survive a pull request.
"""
from __future__ import annotations

import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
TOKENS = ROOT / "design" / "tokens.json"

BANNER = "/* GENERATED by tools/gen_tokens.py from design/tokens.json. Do not edit. */"
BANNER_HASH = "// GENERATED by tools/gen_tokens.py from design/tokens.json. Do not edit."


def load() -> dict:
    with TOKENS.open(encoding="utf-8") as fh:
        return json.load(fh)


def flatten(node: dict, prefix: str = "") -> list[tuple[str, str]]:
    """Walks the token tree, yielding (kebab-name, value) for every leaf."""
    out: list[tuple[str, str]] = []
    for key, val in node.items():
        if key.startswith("$"):
            continue
        name = f"{prefix}-{key}" if prefix else key
        if isinstance(val, dict):
            if "value" in val:
                out.append((name, str(val["value"])))
                # Dark-mode override for severity colours travels with its token.
                if "onDark" in val:
                    out.append((f"{name}-on-dark", str(val["onDark"])))
            else:
                out.extend(flatten(val, name))
    return out


def camel(kebab: str) -> str:
    head, *tail = kebab.split("-")
    return head + "".join(p[:1].upper() + p[1:] for p in tail)


def pascal(kebab: str) -> str:
    c = camel(kebab)
    return c[:1].upper() + c[1:]


# --------------------------------------------------------------------------- CSS

def emit_css(tokens: dict) -> str:
    light = flatten(tokens["color"]["light"], "color-light")
    dark = flatten(tokens["color"]["dark"], "color-dark")
    rest = []
    for group in ("brand", "severity", "grade"):
        rest.extend(flatten(tokens["color"][group], f"color-{group}"))
    for group in ("type", "space", "radius", "elevation", "motion", "target"):
        rest.extend(flatten(tokens[group], group))

    lines = [BANNER, "", ":root {"]
    lines.append("  /* --- palette ------------------------------------------------ */")
    for name, value in rest:
        lines.append(f"  --{name}: {value};")
    lines.append("")
    lines.append("  /* --- light theme (default) ---------------------------------- */")
    for name, value in light:
        lines.append(f"  --{name.replace('color-light-', 'c-')}: {value};")
    lines.append("")
    lines.append("  /* --- semantic aliases resolved per theme -------------------- */")
    for alias in ("paper", "surface", "surfaceSunk", "ink", "inkMuted", "inkFaint", "hairline"):
        lines.append(f"  --{alias}: var(--c-{alias});")
    for sev in tokens["color"]["severity"]:
        if sev.startswith("$"):
            continue
        lines.append(f"  --sev-{sev}: var(--color-severity-{sev});")
    lines.append("  --inner-top: var(--elevation-innerTop);")
    lines.append("  --duration: var(--motion-base);")
    lines.append("}")
    lines.append("")
    lines.append('[data-theme="dark"] {')
    for name, value in dark:
        lines.append(f"  --{name.replace('color-dark-', 'c-')}: {value};")
    for sev in tokens["color"]["severity"]:
        if sev.startswith("$"):
            continue
        lines.append(f"  --sev-{sev}: var(--color-severity-{sev}-on-dark);")
    lines.append("  --inner-top: var(--elevation-innerTopDark);")
    lines.append("}")
    lines.append("")
    lines.append("@media (prefers-reduced-motion: reduce) {")
    lines.append("  :root { --duration: var(--motion-reduced); }")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


# ------------------------------------------------------------------------ Kotlin

def emit_kotlin(tokens: dict, package: str = "com.mume.app.ui") -> str:
    """Compose token object.

    The same source serves the Android app and the desktop app: Compose
    Multiplatform reuses androidx.compose.ui package names verbatim, so only the
    package declaration differs. Emitting twice rather than sharing a module
    keeps :core free of any UI dependency.
    """

    def hex_to_argb(h: str) -> str:
        return "0xFF" + h.lstrip("#").upper()

    lines = [
        BANNER_HASH,
        f"package {package}",
        "",
        "import androidx.compose.ui.graphics.Color",
        "import androidx.compose.ui.unit.dp",
        "import androidx.compose.ui.unit.sp",
        "",
        "/**",
        " * Design tokens, generated from design/tokens.json.",
        " *",
        " * Compose views must reference these rather than literal colours or sizes;",
        " * `tools/check_tokens.py` fails the build if this file drifts from source.",
        " */",
        "object MumeTokens {",
        "",
        "    object Light {",
    ]
    for name, value in flatten(tokens["color"]["light"]):
        lines.append(f"        val {camel(name)} = Color({hex_to_argb(value)})")
    lines += ["    }", "", "    object Dark {"]
    for name, value in flatten(tokens["color"]["dark"]):
        lines.append(f"        val {camel(name)} = Color({hex_to_argb(value)})")
    lines += ["    }", "", "    object Severity {"]
    for name, node in tokens["color"]["severity"].items():
        if name.startswith("$"):
            continue
        lines.append(f"        val {camel(name)} = Color({hex_to_argb(node['value'])})")
        lines.append(f"        val {camel(name)}OnDark = Color({hex_to_argb(node['onDark'])})")
        lines.append(f'        const val {name.upper()}_LABEL = "{node["label"]}"')
    lines += ["    }", "", "    object Brand {"]
    for name, node in tokens["color"]["brand"].items():
        if name.startswith("$"):
            continue
        lines.append(f"        val {camel(name)} = Color({hex_to_argb(node['value'])})")
    lines += ["    }", "", "    object Space {"]
    for name, node in tokens["space"].items():
        if name.startswith("$"):
            continue
        rem = float(str(node["value"]).replace("rem", "") or 0)
        lines.append(f"        val s{name} = {rem * 16:.0f}.dp")
    lines += ["    }", "", "    object Radius {"]
    for name, node in tokens["radius"].items():
        if name.startswith("$"):
            continue
        v = str(node["value"])
        dp = 999 if v.endswith("px") else float(v.replace("rem", "")) * 16
        lines.append(f"        val {camel(name)} = {dp:.0f}.dp")
    lines += ["    }", "", "    object TypeScale {"]
    for name, node in tokens["type"]["scale"].items():
        if name.startswith("$"):
            continue
        lines.append(f"        val {camel(name)} = {node['px']:.1f}.sp")
    # --- Elevation -----------------------------------------------------------
    # Previously omitted entirely, which is why DD-13's "very soft diffused
    # ambient shadows" reached the web and never reached either app: the token
    # existed, generated to CSS, and had no Kotlin counterpart to reference.
    elev = tokens["elevationCompose"]
    spring = str(tokens["motion"]["spring"]["value"])
    pts = [q.strip() for q in spring[spring.index("(") + 1:spring.index(")")].split(",")]

    lines += [
        "    }",
        "",
        "    /**",
        "     * Shadow spec for `Modifier.shadow(dp, shape, clip = false, ambientColor, spotColor)`.",
        "     *",
        "     * Deliberately not `Surface(shadowElevation =)`, which draws a tight grey",
        "     * Material shadow -- precisely the harsh drop shadow DD-13 rejects.",
        "     */",
        "    data class ShadowSpec(",
        "        val dp: androidx.compose.ui.unit.Dp,",
        "        val ambient: Color,",
        "        val spot: Color",
        "    )",
        "",
        "    /**",
        "     * On DARK every shadow is transparent. A shadow is invisible on near-black",
        "     * at any alpha, so a dark surface separates from its background by luminance",
        "     * and a 1dp top highlight instead. That is what a first-class dark theme,",
        "     * as opposed to an inversion, means concretely.",
        "     */",
        "    object Elevation {",
    ]
    for _n, _v in elev.items():
        if _n.startswith("$"):
            continue
        lines.append(
            "        val %s = ShadowSpec(%s.dp, Color(0x%s), Color(0x%s))"
            % (camel(_n), _v["dp"], _v["ambient"].lstrip("#").upper(), _v["spot"].lstrip("#").upper())
        )
    lines += [
        "",
        "        val none = ShadowSpec(0.dp, Color.Transparent, Color.Transparent)",
        "",
        "        /** Replaces the shadow on dark: a 1dp lit top edge. */",
        "        val innerTopDark = Color(0x0FFFFFFF)",
        "        val innerTopLight = Color(0xA6FFFFFF)",
        "    }",
        "",
        "    object Motion {",
        "        const val FAST_MS = %d" % int(str(tokens["motion"]["fast"]["value"]).replace("ms", "")),
        "        const val BASE_MS = %d" % int(str(tokens["motion"]["base"]["value"]).replace("ms", "")),
        "        const val SLOW_MS = %d" % int(str(tokens["motion"]["slow"]["value"]).replace("ms", "")),
        "",
        "        /**",
        "         * The Reduce Motion duration. Defined in tokens.json since the design",
        "         * meeting and never generated, so no Kotlin code could honour DD-10",
        "         * even in principle.",
        "         */",
        "        const val REDUCED_MS = %d" % int(str(tokens["motion"]["reduced"]["value"]).replace("ms", "")),
        "",
        "        /**",
        "         * DD-10's single spring. The durations shipped; the easing did not, so",
        "         * every animation silently ran Compose's default FastOutSlowIn.",
        "         */",
        "        val SPRING = androidx.compose.animation.core.CubicBezierEasing(%sf, %sf, %sf, %sf)"
        % (float(pts[0]), float(pts[1]), float(pts[2]), float(pts[3])),
        "    }",
        "",
        "    /**",
        "     * Minimum FINGER target. The desktop build is pointer-driven, where the",
        "     * applicable bar is WCAG 2.2 SC 2.5.8 (24x24); 48dp there spends roughly a",
        "     * third of a screenful on clearance nobody needs. Use [MinPointerTarget].",
        "     */",
        "    val MinTouchTarget = %d.dp" % int(str(tokens["target"]["android"]["value"]).replace("dp", "")),
        "",
        "    /** Minimum POINTER target. 32dp clears WCAG 2.2 SC 2.5.8 with margin. */",
        "    val MinPointerTarget = 32.dp",
        "}",
        "",
    ]
    return "\n".join(lines)


# ------------------------------------------------------------------------- Swift

def emit_swift(tokens: dict) -> str:
    def comps(h: str) -> str:
        h = h.lstrip("#")
        r, g, b = (int(h[i:i + 2], 16) / 255 for i in (0, 2, 4))
        return f"red: {r:.4f}, green: {g:.4f}, blue: {b:.4f}"

    lines = [
        BANNER_HASH,
        "import SwiftUI",
        "",
        "/// Design tokens, generated from design/tokens.json.",
        "///",
        "/// SwiftUI views must reference these rather than literal colours or sizes;",
        "/// `tools/check_tokens.py` fails the build if this file drifts from source.",
        "public enum MumeTokens {",
        "",
        "    public enum Light {",
    ]
    for name, value in flatten(tokens["color"]["light"]):
        lines.append(f"        public static let {camel(name)} = Color({comps(value)})")
    lines += ["    }", "", "    public enum Dark {"]
    for name, value in flatten(tokens["color"]["dark"]):
        lines.append(f"        public static let {camel(name)} = Color({comps(value)})")
    lines += ["    }", "", "    public enum Severity {"]
    for name, node in tokens["color"]["severity"].items():
        if name.startswith("$"):
            continue
        lines.append(f"        public static let {camel(name)} = Color({comps(node['value'])})")
        lines.append(f"        public static let {camel(name)}OnDark = Color({comps(node['onDark'])})")
        lines.append(f'        public static let {camel(name)}Label = "{node["label"]}"')
    lines += ["    }", "", "    public enum Brand {"]
    for name, node in tokens["color"]["brand"].items():
        if name.startswith("$"):
            continue
        lines.append(f"        public static let {camel(name)} = Color({comps(node['value'])})")
    lines += ["    }", "", "    public enum Space {"]
    for name, node in tokens["space"].items():
        if name.startswith("$"):
            continue
        rem = float(str(node["value"]).replace("rem", "") or 0)
        lines.append(f"        public static let s{name}: CGFloat = {rem * 16:.0f}")
    lines += ["    }", "", "    public enum Radius {"]
    for name, node in tokens["radius"].items():
        if name.startswith("$"):
            continue
        v = str(node["value"])
        pt = 999 if v.endswith("px") else float(v.replace("rem", "")) * 16
        lines.append(f"        public static let {camel(name)}: CGFloat = {pt:.0f}")
    lines += ["    }", "", "    public enum TypeScale {"]
    for name, node in tokens["type"]["scale"].items():
        if name.startswith("$"):
            continue
        lines.append(f"        public static let {camel(name)}: CGFloat = {node['px']:.1f}")
    lines += [
        "    }",
        "",
        "    public enum Motion {",
        f'        public static let fast: Double = {int(str(tokens["motion"]["fast"]["value"]).replace("ms", "")) / 1000}',
        f'        public static let base: Double = {int(str(tokens["motion"]["base"]["value"]).replace("ms", "")) / 1000}',
        f'        public static let slow: Double = {int(str(tokens["motion"]["slow"]["value"]).replace("ms", "")) / 1000}',
        "    }",
        "",
        "    /// Minimum touch target. Enforced by the design gate checklist.",
        f'    public static let minTouchTarget: CGFloat = {int(str(tokens["target"]["ios"]["value"]).replace("pt", ""))}',
        "}",
        "",
    ]
    return "\n".join(lines)


def write(path: pathlib.Path, content: str) -> bool:
    path.parent.mkdir(parents=True, exist_ok=True)
    existing = path.read_text(encoding="utf-8") if path.exists() else None
    if existing == content:
        print(f"  unchanged  {path.relative_to(ROOT)}")
        return False
    path.write_text(content, encoding="utf-8", newline="\n")
    print(f"  written    {path.relative_to(ROOT)}  ({len(content):,} bytes)")
    return True


def main() -> int:
    tokens = load()
    print(f"Reading {TOKENS.relative_to(ROOT)} (v{tokens['$version']})")
    write(ROOT / "design" / "tokens.css", emit_css(tokens))
    write(ROOT / "app" / "src" / "main" / "java" / "com" / "mume" / "app" / "ui" / "MumeTokens.kt",
          emit_kotlin(tokens))
    write(ROOT / "desktop" / "src" / "main" / "kotlin" / "com" / "mume" / "desktop" / "ui" / "MumeTokens.kt",
          emit_kotlin(tokens, package="com.mume.desktop.ui"))
    write(ROOT / "ios" / "MumeCore" / "Sources" / "MumeCore" / "MumeTokens.swift", emit_swift(tokens))
    print("Done.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
